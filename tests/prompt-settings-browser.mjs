import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {DEFAULT_CANDIDATE_PROMPT} from '../src/candidate-prompt.js';

const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const openCandidates=async()=>{
  await page.getByRole('tab',{name:'候选食物'}).click();
  await page.locator('summary').filter({hasText:'候选生成提示词'}).click();
  await page.locator('summary').filter({hasText:'实际发送提示词'}).click();
};
const preview=async()=>JSON.parse(await page.getByLabel('实际发送提示词',{exact:true}).inputValue()).prompt;
try{
  await page.goto(process.env.WORKBENCH_URL||'http://127.0.0.1:4174/');
  await openCandidates();
  assert.equal(await page.getByLabel('候选提示词模板',{exact:true}).inputValue(),DEFAULT_CANDIDATE_PROMPT);
  await page.getByLabel('每槽位候选数量',{exact:true}).fill('5');
  assert.equal((await preview())['## Examples'].输出.slotFoods[0].foods.length,5);
  const custom=JSON.parse(DEFAULT_CANDIDATE_PROMPT);
  custom.prompt['## Rules'].push('优先使用超市常见食物');
  const edited=JSON.stringify(custom,null,2);
  await page.getByLabel('候选提示词模板',{exact:true}).fill(edited);
  assert.ok(await page.getByRole('button',{name:'AI生成候选食物',exact:true}).isDisabled());
  await page.getByRole('button',{name:'保存并应用提示词',exact:true}).click();
  await page.getByLabel('每槽位候选数量',{exact:true}).fill('10');
  assert.ok((await preview())['## Rules'].includes('优先使用超市常见食物'));
  assert.equal((await preview())['## Examples'].输出.slotFoods[0].foods.length,10);
  await page.getByLabel('每槽位候选数量',{exact:true}).fill('5');
  await page.reload();await openCandidates();
  assert.equal(await page.getByLabel('每槽位候选数量',{exact:true}).inputValue(),'5');
  assert.equal(await page.getByLabel('候选提示词模板',{exact:true}).inputValue(),edited);
  await page.getByLabel('候选提示词模板',{exact:true}).fill(edited+' ');
  await page.reload();await openCandidates();
  assert.ok(await page.getByRole('button',{name:'AI生成候选食物',exact:true}).isDisabled());
  assert.equal(await page.getByLabel('候选提示词模板',{exact:true}).inputValue(),edited+' ');
  await page.getByRole('button',{name:'恢复已保存版本',exact:true}).click();
  assert.equal(await page.getByLabel('候选提示词模板',{exact:true}).inputValue(),edited);
  await page.getByRole('button',{name:'配置模型',exact:true}).click();
  await page.getByLabel('API Key',{exact:true}).fill('fake-key');
  await page.getByRole('button',{name:'完成配置',exact:true}).click();
  let requests=0;
  await page.route('**/api/preprocess',async route=>{
    requests++;
    const body=route.request().postDataJSON();
    assert.equal(body.count,5);
    const prompt=JSON.parse(body.prompt).prompt;
    assert.ok(prompt['## Rules'].includes('优先使用超市常见食物'));
    assert.ok(!body.prompt.includes('{{'));
    assert.ok(!body.prompt.includes('15种'));
    assert.equal(prompt['## Examples'].输出.slotFoods[0].foods.length,5);
    const parsed={status:'OK',goal:'fat_loss',planName:prompt['## Input'].planName,slotFoods:prompt['## Input'].slots.map(slot=>({slot,foods:Array.from({length:5},(_,i)=>`${slot}候选${i+1}`)}))};
    await route.fulfill({json:{parsed,content:JSON.stringify(parsed),model:'mock',durationMs:10,timestamp:new Date().toISOString()}});
  });
  await page.getByRole('button',{name:'AI生成候选食物',exact:true}).click();
  await page.getByText('AI结果已返回，请检查并应用',{exact:true}).waitFor();
  await page.getByRole('button',{name:'应用候选列表',exact:true}).click();
  assert.match(await page.getByTestId('candidate-apply-feedback').innerText(),/25 种候选食物/);
  assert.equal(requests,1);
  await page.getByLabel('每槽位候选数量',{exact:true}).fill('2');
  assert.ok(await page.getByRole('button',{name:'AI生成候选食物',exact:true}).isDisabled());
  await page.getByText('每槽位候选数量需要为3–20的整数',{exact:true}).waitFor();
  await page.getByLabel('每槽位候选数量',{exact:true}).fill('5');
  await page.screenshot({path:'test-results/prompt-settings-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:'test-results/prompt-settings-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'恢复默认提示词',exact:true}).click();
  assert.equal(await page.getByLabel('候选提示词模板',{exact:true}).inputValue(),DEFAULT_CANDIDATE_PROMPT);
  assert.equal(await page.getByLabel('每槽位候选数量',{exact:true}).inputValue(),'5');
  assert.ok(!(await preview())['## Rules'].includes('优先使用超市常见食物'));
  assert.deepEqual(errors,[]);
  console.log('Prompt editing, save/reset, draft persistence, live counts, actual mocked request and desktop/mobile layout passed.');
}finally{await browser.close();}
